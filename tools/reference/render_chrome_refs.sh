#!/usr/bin/env bash
# Renders the visual-regression fixtures with headless Google Chrome.
#
# Chrome is the reference because the Studio exports PNGs by rasterising its
# SVG in the browser (src/export/download.ts → svgToPng). These references
# therefore show what Studio users actually see.
#
# Output: tests/fixtures/chrome-ref/<frame>__<theme>__<file>.png at 128×128,
# transparent background, CPU rasterisation (--disable-gpu), device scale 1.
# References are platform-specific for text: they are produced on macOS, where
# the RVHL family list resolves to Arial (labels) and DIN Alternate (numerals).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
CHROME="${CHROME:-/Applications/Google Chrome.app/Contents/MacOS/Google Chrome}"
SRC="$ROOT/assets/rvhl/pictograms"
OUT="$ROOT/tests/fixtures/chrome-ref"
LIST="$ROOT/tests/fixtures/visual-fixtures.txt"
SIZE=128
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

[[ -x "$CHROME" ]] || { echo "Chrome not found: set CHROME=/path/to/chrome" >&2; exit 1; }
mkdir -p "$OUT"
VERSION="$("$CHROME" --version)"

while read -r rel _; do
  [[ -z "$rel" || "$rel" == \#* ]] && continue
  frame="${rel%%/*}"; rest="${rel#*/}"; theme="${rest%%/*}"; file="${rest#*/}"
  name="${frame}__${theme}__${file%.svg}.png"
  svg="$(sed "s/width=\"64\" height=\"64\"/width=\"$SIZE\" height=\"$SIZE\" style=\"display:block\"/" "$SRC/$rel")"
  printf '<!doctype html><html><body style="margin:0;background:transparent">%s</body></html>' "$svg" > "$TMP/page.html"
  "$CHROME" --headless=new --disable-gpu --hide-scrollbars --force-device-scale-factor=1 \
    --default-background-color=00000000 --window-size=$SIZE,$SIZE \
    --screenshot="$OUT/$name" "file://$TMP/page.html" >/dev/null 2>&1
  echo "  $name"
done < "$LIST"

cat > "$OUT/README.md" <<EOF
# Chrome reference renderings

Generated by \`tools/reference/render_chrome_refs.sh\` from \`assets/rvhl/pictograms\`.

- Renderer: $VERSION, headless, \`--disable-gpu\`, device scale 1
- Size: ${SIZE}×${SIZE}, transparent background
- Host: $(sw_vers -productName 2>/dev/null || uname -s) $(sw_vers -productVersion 2>/dev/null || uname -r) $(uname -m)
- Fixture list: \`tests/fixtures/visual-fixtures.txt\`

Text references depend on installed fonts (macOS: Arial, DIN Alternate).
EOF
echo "wrote $(ls "$OUT"/*.png | wc -l | tr -d ' ') references ($VERSION)"
